def 一轮并发(轮: int):
    """每轮开一扇唯一新窗（按轮偏移分钟），再并发「关该窗」与「同窗在途事件」。

    同库、唯一窗键/事件号/批次号，贴近真实多连接并发；写锁把交错线性化为两种自洽序之一。
    """
    分 = 10 + 轮
    窗起 = f"2026-11-22T12:{分:02d}:00Z"
    wk = f"房A|{窗起}"
    在途时 = f"2026-11-22T12:{分:02d}:20Z"
    抬水位时 = f"2026-11-22T12:{分 + 1:02d}:05Z"
    撞处理时 = f"2026-11-22T12:{分 + 1:02d}:06Z"
    装(
        [
            {"事件编号": f"P{轮}", "房间键": "房A", "事件类型": "点赞",
             "事件时": f"2026-11-22T12:{分:02d}:10Z",
             "处理时": f"2026-11-22T12:{分:02d}:11Z",
             "观众键": "观p", "点赞增量": 2, "送礼额": 0},
        ],
        f"批-并发铺垫-{轮}",
    )

    def 推高水位关窗():
        装(
            [{"事件编号": f"G{轮}", "房间键": "房A", "事件类型": "点赞",
              "事件时": 抬水位时, "处理时": 撞处理时,
              "观众键": "观g", "点赞增量": 1, "送礼额": 0}],
            f"批-并发关-{轮}",
        )

    def 推同窗在途():
        装(
            [{"事件编号": f"D{轮}", "房间键": "房A", "事件类型": "点赞",
              "事件时": 在途时, "处理时": 撞处理时,
              "观众键": "观d", "点赞增量": 5, "送礼额": 0}],
            f"批-并发收-{轮}",
        )

    t1 = threading.Thread(target=推高水位关窗)
    t2 = threading.Thread(target=推同窗在途)
    t1.start(); t2.start(); t1.join(); t2.join()

    conn = 连接()
    try:
        w = conn.execute("SELECT * FROM 热度窗 WHERE 窗键=?", (wk,)).fetchone()
        f = conn.execute("SELECT * FROM 关窗发射 WHERE 窗键=?", (wk,)).fetchone()
        d = conn.execute("SELECT * FROM 互动事件 WHERE 事件编号=?", (f"D{轮}",)).fetchone()
        戳 = conn.execute("SELECT * FROM 发射冻结戳 WHERE 窗键=?", (wk,)).fetchone()
        视图 = 发射服务.组装发射视图(conn, w)
        return w, f, d, 视图, 戳
    finally:
        conn.close()


